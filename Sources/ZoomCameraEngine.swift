import Foundation
import CoreGraphics

public final class ZoomCameraEngine {

    // Live state tracking
    private var liveCamera = CameraRenderState()
    private var liveSmoothedMouse = CGPoint(x: 0.5, y: 0.5)
    private var liveTargetFocus = CGPoint(x: 0.5, y: 0.5)
    private var liveZoomVelocity: CGFloat = 0.0
    private var liveFocusVelocity = CGPoint.zero
    private var liveZoomHoldUntil: TimeInterval = 0
    private var lastMouseMoveTime: TimeInterval = 0
    private var lastRawMouse: CGPoint = CGPoint(x: 0.5, y: 0.5)
    private var liveCursorOpacity: CGFloat = 1.0

    public init() {}

    // MARK: - Auto-Generate Zoom Segments from Clicks

    public static func generateZoomSegments(
        from clicks: [ClickEvent],
        totalDuration: TimeInterval,
        settings: StudioSettings
    ) -> [ZoomSegment] {
        guard settings.autoZoomEnabled, !clicks.isEmpty else { return [] }

        let sortedClicks = clicks.sorted { $0.timestamp < $1.timestamp }
        let lead = settings.preClickLeadTime
        let hold = settings.zoomHoldDuration
        let mergeThreshold = settings.zoomSpeed.transitionDuration * 1.4

        var segments: [ZoomSegment] = []

        for click in sortedClicks {
            let start = max(0.0, click.timestamp - lead)
            let end = totalDuration > 0 ? min(totalDuration, click.timestamp + hold) : (click.timestamp + hold)

            if var last = segments.last, start <= last.endTime + mergeThreshold {
                last.endTime = max(last.endTime, end)
                segments[segments.count - 1] = last
            } else {
                let seg = ZoomSegment(
                    startTime: start,
                    endTime: max(start + 0.4, end),
                    focusPoint: clampNormalized(click.location),
                    zoomScale: settings.defaultZoomScale,
                    isAutoGenerated: true
                )
                segments.append(seg)
            }
        }

        return segments
    }

    // MARK: - OBS-Style Live Step (Critically Damped Optical Zoom into Cursor)

    public func triggerLiveClick(at normalizedPoint: CGPoint, now: TimeInterval, settings: StudioSettings) {
        guard settings.autoZoomEnabled else { return }
        let pt = Self.clampNormalized(normalizedPoint)
        liveTargetFocus = pt
        // If we were completely unzoomed, snap the un-clamped optical pivot right to the click point
        // (clampViewportCenter keeps visual center at 0.5 while zoom == 1.0, so there is zero jump!)
        if liveCamera.zoom < 1.015 {
            liveCamera.focusCenter = pt
            liveFocusVelocity = .zero
        }
        liveZoomHoldUntil = now + settings.zoomHoldDuration
    }

    public func stepLive(
        dt: Double,
        rawMouse: CGPoint,
        isLeftDown: Bool,
        isRightDown: Bool,
        recentClicks: [ClickEvent],
        now: TimeInterval,
        settings: StudioSettings
    ) -> (camera: CameraRenderState, cursor: CursorRenderState) {
        let clampedMouse = Self.clampNormalized(rawMouse)
        let safeDt = CGFloat(max(1.0 / 240.0, min(0.05, dt)))

        // Detect mouse movement for idle hiding
        let moveDist = hypot(clampedMouse.x - lastRawMouse.x, clampedMouse.y - lastRawMouse.y)
        if moveDist > 0.0008 || isLeftDown || isRightDown {
            lastMouseMoveTime = now
        }
        lastRawMouse = clampedMouse

        // 1. Smooth mouse cursor interpolation (OBS inertia)
        if settings.smoothMouseMovement {
            let speed = max(4.0, min(50.0, CGFloat(settings.mouseSmoothingFactor) * 75.0))
            let alpha = 1.0 - exp(-speed * safeDt)
            liveSmoothedMouse.x += (clampedMouse.x - liveSmoothedMouse.x) * alpha
            liveSmoothedMouse.y += (clampedMouse.y - liveSmoothedMouse.y) * alpha
        } else {
            liveSmoothedMouse = clampedMouse
        }

        // 2. Cursor opacity (idle fade)
        let targetOpacity: CGFloat
        if !settings.showCursor {
            targetOpacity = 0.0
        } else if settings.hideCursorWhenIdle && (now - lastMouseMoveTime) > 2.0 {
            targetOpacity = 0.0
        } else {
            targetOpacity = 1.0
        }
        liveCursorOpacity += (targetOpacity - liveCursorOpacity) * min(1.0, safeDt * 8.0)

        // 3. Critically Damped Spring Zoom (OBS Zoom-to-Mouse feel)
        let isZoomActive = settings.autoZoomEnabled && (now < liveZoomHoldUntil)
        let targetZoom: CGFloat = isZoomActive ? settings.defaultZoomScale : 1.0

        if isZoomActive {
            if settings.followMouseWhenZoomed {
                // Deadzone + smooth follow like OBS zoom-to-mouse
                let dx = liveSmoothedMouse.x - liveTargetFocus.x
                let dy = liveSmoothedMouse.y - liveTargetFocus.y
                let dist = hypot(dx, dy)
                if dist > 0.015 {
                    let followSpeed = max(2.0, CGFloat(settings.panSmoothing) * 32.0)
                    let followAlpha = 1.0 - exp(-followSpeed * safeDt)
                    liveTargetFocus.x += dx * followAlpha
                    liveTargetFocus.y += dy * followAlpha
                }
            }
        } else if liveCamera.zoom < 1.01 {
            // While unzoomed, keep optical pivot at cursor so the next zoom goes straight into the cursor!
            liveTargetFocus = liveSmoothedMouse
            liveCamera.focusCenter = liveSmoothedMouse
        }

        // Critically damped spring step for Zoom
        let omega = settings.zoomSpeed.liveSpringSpeed * 1.35
        let zoomStep = Self.criticallyDampedSpring(
            current: liveCamera.zoom,
            target: targetZoom,
            velocity: &liveZoomVelocity,
            omega: omega,
            dt: safeDt
        )
        liveCamera.zoom = max(1.0, zoomStep)
        if targetZoom == 1.0 && abs(liveCamera.zoom - 1.0) < 0.001 {
            liveCamera.zoom = 1.0
            liveZoomVelocity = 0.0
        }

        // Critically damped spring step for Focus X & Y
        var vx = liveFocusVelocity.x
        var vy = liveFocusVelocity.y
        let newFx = Self.criticallyDampedSpring(
            current: liveCamera.focusCenter.x,
            target: liveTargetFocus.x,
            velocity: &vx,
            omega: omega * 1.1,
            dt: safeDt
        )
        let newFy = Self.criticallyDampedSpring(
            current: liveCamera.focusCenter.y,
            target: liveTargetFocus.y,
            velocity: &vy,
            omega: omega * 1.1,
            dt: safeDt
        )
        liveFocusVelocity = CGPoint(x: vx, y: vy)
        liveCamera.focusCenter = Self.clampNormalized(CGPoint(x: newFx, y: newFy))

        // Note: We return the clamped viewport center for rendering
        let renderedCamera = CameraRenderState(
            zoom: liveCamera.zoom,
            focusCenter: Self.clampViewportCenter(liveCamera.focusCenter, zoom: liveCamera.zoom)
        )

        // 4. Active click ripples
        var ripples: [ActiveClickRipple] = []
        if settings.clickRippleEnabled {
            let rippleDur = max(0.15, settings.clickRippleDuration)
            for click in recentClicks {
                let age = now - click.timestamp
                if age >= 0 && age <= rippleDur {
                    ripples.append(
                        ActiveClickRipple(
                            location: click.location,
                            progress: CGFloat(age / rippleDur),
                            isRightClick: click.isRightClick
                        )
                    )
                }
            }
        }

        let cursorState = CursorRenderState(
            location: liveSmoothedMouse,
            isPressed: isLeftDown || isRightDown,
            opacity: liveCursorOpacity,
            ripples: ripples
        )

        return (renderedCamera, cursorState)
    }

    /// Exact analytical solution for a critically damped spring: C2-continuous velocity, zero overshoot, butter-smooth like OBS/Screen Studio
    private static func criticallyDampedSpring(
        current: CGFloat,
        target: CGFloat,
        velocity: inout CGFloat,
        omega: CGFloat,
        dt: CGFloat
    ) -> CGFloat {
        let delta = current - target
        let expTerm = exp(-omega * dt)
        let temp = (velocity + omega * delta) * dt
        let newPos = target + (delta + temp) * expTerm
        velocity = (velocity - omega * temp) * expTerm
        return newPos
    }

    // MARK: - Deterministic Timeline Evaluation (Playback & MP4 Export)

    public static func evaluateTimeline(
        at time: TimeInterval,
        settings: StudioSettings,
        zoomSegments: [ZoomSegment],
        mouseSamples: [MouseSample],
        clickEvents: [ClickEvent]
    ) -> (camera: CameraRenderState, cursor: CursorRenderState) {

        let (cursorPos, isPressed, isIdle) = evaluateCursorTrack(
            at: time,
            samples: mouseSamples,
            settings: settings
        )

        var ripples: [ActiveClickRipple] = []
        if settings.clickRippleEnabled {
            let dur = max(0.15, settings.clickRippleDuration)
            for click in clickEvents {
                let dt = time - click.timestamp
                if dt >= 0 && dt <= dur {
                    ripples.append(
                        ActiveClickRipple(
                            location: click.location,
                            progress: CGFloat(dt / dur),
                            isRightClick: click.isRightClick
                        )
                    )
                }
            }
        }

        let cursorOpacity: CGFloat
        if !settings.showCursor {
            cursorOpacity = 0.0
        } else if settings.hideCursorWhenIdle && isIdle {
            cursorOpacity = 0.0
        } else {
            cursorOpacity = 1.0
        }

        let cursorState = CursorRenderState(
            location: cursorPos,
            isPressed: isPressed,
            opacity: cursorOpacity,
            ripples: ripples
        )

        let transitionDur = settings.zoomSpeed.transitionDuration
        var bestWeight: CGFloat = 0.0
        var activeTargetZoom: CGFloat = 1.0
        var activeFocusPoint = cursorPos

        for seg in zoomSegments {
            let inStart = seg.startTime - transitionDur * 0.35
            let outEnd = seg.endTime + transitionDur

            guard time >= inStart && time <= outEnd else { continue }

            let weight: CGFloat
            if time < seg.startTime + transitionDur * 0.65 {
                let raw = (time - inStart) / max(0.05, transitionDur)
                weight = smootherStep(CGFloat(raw))
            } else if time > seg.endTime {
                let raw = 1.0 - (time - seg.endTime) / max(0.05, transitionDur)
                weight = smootherStep(CGFloat(raw))
            } else {
                weight = 1.0
            }

            if weight > bestWeight {
                bestWeight = weight
                activeTargetZoom = seg.zoomScale

                let clickTarget = interpolatedClickFocus(at: time, within: seg, clicks: clickEvents, transition: transitionDur)
                if settings.followMouseWhenZoomed {
                    let smoothPanMouse = evaluateSmoothCameraPan(
                        at: time,
                        samples: mouseSamples,
                        fallback: clickTarget,
                        panSmoothing: settings.panSmoothing
                    )
                    let mouseBlend: CGFloat = 0.55
                    activeFocusPoint = CGPoint(
                        x: clickTarget.x * (1.0 - mouseBlend) + smoothPanMouse.x * mouseBlend,
                        y: clickTarget.y * (1.0 - mouseBlend) + smoothPanMouse.y * mouseBlend
                    )
                } else {
                    activeFocusPoint = clickTarget
                }
            }
        }

        let currentZoom = 1.0 + (activeTargetZoom - 1.0) * bestWeight
        let clampedCenter = clampViewportCenter(activeFocusPoint, zoom: currentZoom)

        return (
            CameraRenderState(zoom: currentZoom, focusCenter: clampedCenter),
            cursorState
        )
    }

    private static func evaluateSmoothCameraPan(
        at time: TimeInterval,
        samples: [MouseSample],
        fallback: CGPoint,
        panSmoothing: CGFloat
    ) -> CGPoint {
        guard !samples.isEmpty else { return fallback }
        var low = 0
        var high = samples.count - 1
        while low < high {
            let mid = (low + high + 1) / 2
            if samples[mid].timestamp <= time {
                low = mid
            } else {
                high = mid - 1
            }
        }
        let baseIndex = low
        let startIdx = max(0, baseIndex - 14)

        var smoothed = samples[startIdx].location
        var prevTime = samples[startIdx].timestamp
        let speed = max(2.0, min(18.0, Double(panSmoothing) * 28.0))

        if startIdx < baseIndex {
            for i in (startIdx + 1)...baseIndex {
                let s = samples[i]
                let dt = max(0.001, s.timestamp - prevTime)
                let alpha = CGFloat(1.0 - exp(-speed * dt))
                smoothed.x += (s.location.x - smoothed.x) * alpha
                smoothed.y += (s.location.y - smoothed.y) * alpha
                prevTime = s.timestamp
            }
        }
        return clampNormalized(smoothed)
    }

    private static func interpolatedClickFocus(
        at time: TimeInterval,
        within segment: ZoomSegment,
        clicks: [ClickEvent],
        transition: Double
    ) -> CGPoint {
        var firstFocus: CGPoint? = nil
        var currentFocus = segment.focusPoint
        var count = 0

        for c in clicks {
            if c.timestamp < segment.startTime - 0.35 { continue }
            if c.timestamp > segment.endTime + 0.1 { break }
            count += 1
            if count == 1 {
                firstFocus = c.location
                currentFocus = c.location
                continue
            }
            let panStart = c.timestamp - transition * 0.5
            let panEnd = c.timestamp + transition * 0.5
            if time >= panEnd {
                currentFocus = c.location
            } else if time > panStart {
                let u = smootherStep(CGFloat((time - panStart) / max(0.05, panEnd - panStart)))
                currentFocus = CGPoint(
                    x: currentFocus.x + (c.location.x - currentFocus.x) * u,
                    y: currentFocus.y + (c.location.y - currentFocus.y) * u
                )
                break
            } else {
                break
            }
        }
        return firstFocus != nil ? currentFocus : segment.focusPoint
    }

    private static func evaluateCursorTrack(
        at time: TimeInterval,
        samples: [MouseSample],
        settings: StudioSettings
    ) -> (location: CGPoint, isPressed: Bool, isIdle: Bool) {
        guard !samples.isEmpty else {
            return (CGPoint(x: 0.5, y: 0.5), false, false)
        }

        var low = 0
        var high = samples.count - 1
        while low < high {
            let mid = (low + high + 1) / 2
            if samples[mid].timestamp <= time {
                low = mid
            } else {
                high = mid - 1
            }
        }

        let baseIndex = low
        let currentSample = samples[baseIndex]
        let isPressed = currentSample.isLeftDown || currentSample.isRightDown

        var isIdle = false
        if settings.hideCursorWhenIdle && time > 1.8 {
            let lookbackIdx = max(0, baseIndex - 30)
            let oldSample = samples[lookbackIdx]
            let dist = hypot(
                oldSample.location.x - currentSample.location.x,
                oldSample.location.y - currentSample.location.y
            )
            isIdle = (dist <= 0.003 && !isPressed && !oldSample.isLeftDown && !oldSample.isRightDown)
        }

        guard settings.smoothMouseMovement else {
            return (clampNormalized(currentSample.location), isPressed, isIdle)
        }

        // Fixed 12-sample local EMA window (~0.2s) for O(1) constant-time 60fps evaluation
        let startIdx = max(0, baseIndex - 12)
        var smoothed = samples[startIdx].location
        var prevTime = samples[startIdx].timestamp
        let speed = max(3.0, min(45.0, Double(settings.mouseSmoothingFactor) * 65.0))

        if startIdx < baseIndex {
            for i in (startIdx + 1)...baseIndex {
                let s = samples[i]
                let dt = max(0.001, s.timestamp - prevTime)
                let alpha = CGFloat(1.0 - exp(-speed * dt))
                smoothed.x += (s.location.x - smoothed.x) * alpha
                smoothed.y += (s.location.y - smoothed.y) * alpha
                prevTime = s.timestamp
            }
        }

        if baseIndex + 1 < samples.count {
            let next = samples[baseIndex + 1]
            let span = next.timestamp - currentSample.timestamp
            if span > 0.0001 && time > currentSample.timestamp {
                let frac = CGFloat(min(1.0, (time - currentSample.timestamp) / span))
                let rawInterp = CGPoint(
                    x: currentSample.location.x + (next.location.x - currentSample.location.x) * frac,
                    y: currentSample.location.y + (next.location.y - currentSample.location.y) * frac
                )
                let dt = max(0.001, time - prevTime)
                let alpha = CGFloat(1.0 - exp(-speed * dt))
                smoothed.x += (rawInterp.x - smoothed.x) * alpha
                smoothed.y += (rawInterp.y - smoothed.y) * alpha
            }
        }

        return (clampNormalized(smoothed), isPressed, isIdle)
    }

    public static func smootherStep(_ x: CGFloat) -> CGFloat {
        let t = max(0.0, min(1.0, x))
        return t * t * t * (t * (t * 6.0 - 15.0) + 10.0)
    }

    public static func clampNormalized(_ p: CGPoint) -> CGPoint {
        CGPoint(
            x: max(0.0, min(1.0, p.x)),
            y: max(0.0, min(1.0, p.y))
        )
    }

    public static func clampViewportCenter(_ center: CGPoint, zoom: CGFloat) -> CGPoint {
        guard zoom > 1.001 else {
            return CGPoint(x: 0.5, y: 0.5)
        }
        let halfSpan = min(0.5, 0.5 / zoom)
        let minCoord = halfSpan
        let maxCoord = 1.0 - halfSpan
        return CGPoint(
            x: max(minCoord, min(maxCoord, center.x)),
            y: max(minCoord, min(maxCoord, center.y))
        )
    }
}
